import { mkdir, readFile, writeFile } from "node:fs/promises";
import StyleDictionary from "style-dictionary";

const OUT = "build/";
const PRIMITIVES = "src/primitive/**/*.tokens.json";

/** DTCG dimension/duration values are `{ value, unit }` objects; CSS wants `<value><unit>`. */
const unitObjectToCss = {
  type: "value",
  transitive: true,
  filter: (token) => ["dimension", "duration"].includes(token.$type ?? token.type),
  transform: (token) => {
    const v = token.$value ?? token.value;
    return typeof v === "object" && v !== null ? `${v.value}${v.unit}` : v;
  },
};

StyleDictionary.registerTransform({ name: "unit-object/css", ...unitObjectToCss });

const cssTransforms = ["name/kebab", "color/css", "fontFamily/css", "unit-object/css"];

function cssPlatform(theme, selector, onlySemantic) {
  return {
    transforms: cssTransforms,
    buildPath: `${OUT}css/`,
    files: [
      {
        destination: `${theme}.css`,
        format: "css/variables",
        options: { selector, outputReferences: false },
        filter: onlySemantic ? (token) => token.filePath.includes("semantic/") : undefined,
      },
    ],
  };
}

const light = new StyleDictionary({
  source: [PRIMITIVES, "src/semantic/light.tokens.json"],
  platforms: {
    css: cssPlatform("light", ':root, [data-theme="light"]', false),
    json: {
      transforms: cssTransforms,
      buildPath: `${OUT}json/`,
      files: [{ destination: "tokens.json", format: "json/flat" }],
    },
  },
});

const dark = new StyleDictionary({
  source: [PRIMITIVES, "src/semantic/dark.tokens.json"],
  platforms: { css: cssPlatform("dark", '[data-theme="dark"]', true) },
});

await light.buildAllPlatforms();
await dark.buildAllPlatforms();

const header = "/* Generated by @einring/tokens - do not edit. Source: packages/tokens/src */\n";
const [lightCss, darkCss] = await Promise.all([
  readFile(`${OUT}css/light.css`, "utf8"),
  readFile(`${OUT}css/dark.css`, "utf8"),
]);
await mkdir(`${OUT}css`, { recursive: true });
await writeFile(`${OUT}css/tokens.css`, header + lightCss + "\n" + darkCss);
console.log("tokens.css written");
