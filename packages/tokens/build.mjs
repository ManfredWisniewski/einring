import { readFile, writeFile } from "node:fs/promises";
import { buildCmd, loadConfig } from "@terrazzo/cli";
import { Logger } from "@terrazzo/parser";

// Resolve the resolver/config relative to this file regardless of the caller's cwd.
process.chdir(import.meta.dirname);

const logger = new Logger();
const { config, configPath } = await loadConfig({ cmd: "build", flags: {}, logger });
await buildCmd({ config, configPath, flags: {}, logger });

// tokens.css is the single stylesheet the app imports: light block, then dark overrides.
const OUT = "build/css/";
const header = "/* Generated by @einring/tokens - do not edit. Source: packages/tokens/src */\n";
const [lightCss, darkCss] = await Promise.all([
  readFile(`${OUT}light.css`, "utf8"),
  readFile(`${OUT}dark.css`, "utf8"),
]);
await writeFile(`${OUT}tokens.css`, `${header}${lightCss}\n${darkCss}`);
console.log("tokens.css written");
